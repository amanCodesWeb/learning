Four Pillars of OOP

1. Encapsulation
Definition: Wrapping data (properties) and the methods that operate on that data into a single unit (class), while restricting direct access to sensitive data using access modifiers (private, protected).
In simple words: Hide the internal implementation and expose only what's necessary.

2. Abstraction
Definition: Hiding unnecessary implementation details and showing only the essential features to the user.
In simple words: Focus on what an object does, not how it does it.

3. Inheritance
Definition: A mechanism where one class acquires the properties and methods of another class, allowing code reuse and extension.
In simple words: A child class inherits features from a parent class.

4. Polymorphism
Definition: The ability for the same method or interface to have different implementations depending on the object.
In simple words: One interface, many behaviors.
-->


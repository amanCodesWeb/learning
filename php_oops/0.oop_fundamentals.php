What is OOP?

Object-Oriented Programming (OOP) is a programming paradigm that organizes code into objects, where each object represents a real-world entity with its own properties (data) and methods (behavior).

Instead of writing functions that operate on data separately, OOP combines data and the functions that work on it into a single unit called an object. 
